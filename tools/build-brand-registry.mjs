import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { parse } from '../extension/HeuriShield-URL20-XGBoost/src/shared/tldts.js';
import { BRAND_REGISTRY as curated } from '../extension/HeuriShield-URL20-XGBoost/src/analyzer/brand/brand-registry-curated.js';
import { SHARED_HOSTING_ROOTS } from '../extension/HeuriShield-URL20-XGBoost/src/analyzer/brand/shared-hosting.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'data/brand_registry_source');
const raw = gunzipSync(fs.readFileSync(path.join(sourceDir, 'open_company_database_sample.csv.gz')));
const source = JSON.parse(fs.readFileSync(path.join(sourceDir, 'source.json'), 'utf8'));
if (createHash('sha256').update(raw).digest('hex') !== source.sha256) throw Error('Source hash mismatch');

// RFC-style quoted CSV, including escaped quotes, commas and embedded newlines.
function csv(text) {
  const rows = []; let row = [], value = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      if (quoted && text[i + 1] === '"') { value += '"'; i++; }
      else quoted = !quoted;
    } else if (!quoted && (c === ',' || c === '\n')) {
      row.push(value.replace(/\r$/, '')); value = '';
      if (c === '\n') { rows.push(row); row = []; }
    } else value += c;
  }
  if (value || row.length) { row.push(value.replace(/\r$/, '')); rows.push(row); }
  if (quoted) throw Error('Unterminated CSV quote');
  return rows;
}
const compact = value => String(value).normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
const excluded = new Set(['facebook.com', 'linkedin.com', 'instagram.com', 'youtube.com', 'twitter.com', 'x.com', 'linktr.ee', 'bio.site', 'wikipedia.org']);
const generic = new Set(['login', 'signin', 'account', 'secure', 'verify', 'official', 'website', 'home', 'company', 'business', 'group', 'global', 'service', 'services', 'tech', 'technology', 'technologies', 'solutions', 'digital', 'marketing', 'consulting', 'international']);
const [columns, ...rows] = csv(raw.toString('utf8'));
const index = Object.fromEntries(columns.map((name, i) => [name, i]));
const curatedNames = new Set([...curated.values()].map(e => compact(e.name)));
const curatedDomains = new Set([...curated.values()].flatMap(e => e.domains));
const candidates = [];
for (const row of rows) {
  const name = (row[index.company_name] || '').trim();
  const nameKey = compact(name);
  if (name.length < 3 || name.length > 120 || nameKey.length < 4 || /^\d+$/.test(nameKey) || generic.has(nameKey) || curatedNames.has(nameKey)) continue;
  let url;
  try { url = new URL(`https://${row[index.company_domain]}`); } catch { continue; }
  const host = url.hostname.toLowerCase().replace(/\.$/, '');
  const parsed = parse(host, { allowPrivateDomains: true });
  if (url.username || url.password || url.port || url.pathname !== '/' || !parsed.isIcann || parsed.isPrivate || parsed.isIp || !parsed.domain || !parsed.domainWithoutSuffix) continue;
  const domain = parsed.domain;
  const label = compact(parsed.domainWithoutSuffix);
  if (label.length < 5 || /^\d+$/.test(label) || generic.has(label) || curatedDomains.has(domain) || excluded.has(domain) || SHARED_HOSTING_ROOTS.has(domain)) continue;
  if (!(nameKey.includes(label) || label.includes(nameKey))) continue;
  const rank = Number((row[index.web_rank_bucket] || '').match(/Top\s+(\d+)M/i)?.[1] || 999);
  candidates.push({ name, nameKey, domain, label, rank });
}
candidates.sort((a, b) => a.rank - b.rank || a.domain.localeCompare(b.domain, 'en') || a.name.localeCompare(b.name, 'en'));
const names = new Set(), domains = new Set(), imported = [];
for (const candidate of candidates) {
  if (names.has(candidate.nameKey) || domains.has(candidate.domain)) continue;
  names.add(candidate.nameKey); domains.add(candidate.domain);
  imported.push({ name: candidate.name, domains: [candidate.domain], trusted: false,
    domains_complete: false, source: 'fliar_open_company_database', key: candidate.label });
  if (imported.length === 10000) break;
}
if (imported.length < 10000) throw Error(`Only ${imported.length} eligible distinct names; registry not written`);
const dir = path.join(root, 'extension/HeuriShield-URL20-XGBoost/src/analyzer/brand');
fs.writeFileSync(path.join(dir, 'brand-registry-imported.js'),
  '// Generated by tools/build-brand-registry.mjs. Source: Fliar BI / Radar API.\n' +
  '// CC BY-NC 4.0; see data/brand_registry_source/LICENSE and source.json.\n' +
  '// Directory references are candidates, never independent ownership verification.\n' +
  'export const IMPORTED_BRANDS = ' + JSON.stringify(imported) + ';\n');
const summary = { source, source_rows: rows.length, eligible_rows: candidates.length,
  imported_distinct_names: imported.length, curated_distinct_names: curatedNames.size,
  total_distinct_names: imported.length + curatedNames.size,
  selection: 'Valid ICANN company domains; name/domain-label relationship; unique compact names and domains; rank bucket then lexical order; no test labels used.',
  imported_trust: 'Unverified directory candidates. Domain membership is not exhaustive. No automatic verified promotion.' };
fs.writeFileSync(path.join(sourceDir, 'build-summary.json'), JSON.stringify(summary, null, 2));
console.log(JSON.stringify(summary, null, 2));
